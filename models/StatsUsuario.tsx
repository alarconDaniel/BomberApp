export class StatsUsuario {
    public codUsuario: number;
    public monedas: number;
    public racha: number;
    public xp: number;
    public nivel: number;

    constructor(codUsuario: number, monedas: number, racha: number, xp: number, nivel: number) {
        this.codUsuario = codUsuario;
        this.monedas = monedas;
        this.racha = racha;
        this.xp = xp;
        this.nivel = nivel;

    }

}

